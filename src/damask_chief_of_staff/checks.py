def snapshot(root):
    root = Path(root)
    head = git(root, "rev-parse", "HEAD")
    files = git(root, "ls-files", "-co", "--exclude-standard", "-z")
    paths = sorted(set(p.decode("utf-8", "replace") for p in files.stdout.split(b"\0") if p))
    digest = hashlib.sha256(head.stdout)
    captured = 0
    incomplete = files.returncode != 0 or len(paths) > 5000
    for name in paths[:5000]:
        rel = relative(root, name)
        if not rel:
            continue
        p = root / rel
        digest.update(rel.encode())
        try:
            if p.stat().st_size > 1_000_000:
                incomplete = True
                digest.update(str(p.stat().st_mtime_ns).encode())
            else:
                digest.update(p.read_bytes())
            captured += 1
        except OSError:
            digest.update(b"missing")
    changed = git(root, "diff", "--name-only", "--no-ext-diff", "HEAD")
    return {"fingerprint": digest.hexdigest(), "revision": head.stdout.decode().strip() if head.returncode == 0 else "unborn",
        "files_hashed": captured, "partial": incomplete, "attribution": "unknown; shared worktree changes may come from another actor",
        "changed_files": [r for n in changed.stdout.decode().splitlines() if (r := relative(root, n))][:100], "ts": now()}


def register(store, project_id, name, argv, timeout=60):
    store.get("projects", project_id)
    if not name or not isinstance(argv, list) or not argv or any(not isinstance(x, str) or '\x00' in x for x in argv):
        raise ValueError("Register a name and an explicit executable/argument array")
    if not 1 <= timeout <= 300 or len(json.dumps(argv)) > 4000:
        raise ValueError("Check bounds exceeded")
    serialized = json.dumps(argv)
    if text(serialized, 10000) != serialized:
        raise ValueError("Do not put credentials or private content in registered check arguments")
    check = {"id": uid("check_"), "project_id": project_id, "name": text(name, 100), "argv": argv,
        "timeout": timeout, "enabled": True, "authorizer": "local developer", "created": now()}
    with store.transaction() as db:
        store.put("checks", check, db)
        store.audit("check.registered", check, db)
    return check


def run(store, sid, check_id):
    session = store.get("sessions", sid)
    project = store.get("projects", session["project_id"])
    check = store.get("checks", check_id)
    if not project["connected"] or check["project_id"] != project["id"] or not check["enabled"]:
        raise ValueError("Check is not enabled for this connected repository")
    before = snapshot(project["root"])
    # Explicit registration authorizes this command; it is never generated by a model.
    # Deliberately omit credentials and unrelated environment variables.
    safe = {k: v for k, v in os.environ.items() if k in {"PATH", "SYSTEMROOT", "WINDIR", "COMSPEC", "HOME", "USERPROFILE", "TEMP", "TMP", "LANG", "LOCALAPPDATA"}}
    safe["DAMASK_SUPERVISOR"] = "1"
    started = now()
    try:
        from .process import bounded_run
        result = bounded_run(check["argv"], cwd=project["root"], env=safe, timeout=check["timeout"], capture=False)
        code = result["returncode"]
        status = "passed" if code == 0 else "failed"
    except ValueError:
        code, status = None, "timeout"
    except OSError:
        code, status = None, "could-not-start"
    after = snapshot(project["root"])
    changed = before["fingerprint"] != after["fingerprint"]
    event = {"id": uid("e_"), "session_id": sid, "kind": "IndependentCheck", "ts": now(), "data": {
        "check_id": check_id, "name": check["name"], "argv": check["argv"], "result": status, "exit_code": code,
        "before": before, "after": after, "started": started, "duration": now()-started,
        "freshness": "changed-during-check" if changed else "partial-coverage" if before["partial"] else "current-at-completion",
        "output": "not captured", "scope": "Only the registered check; no human acceptance"}}
    with store.transaction() as db:
        add_event(store, db, event)
        session = store.get("sessions", sid, db)
        session["last_ingested"] = now()
        store.put("sessions", session, db)
        if status == "passed" and not changed and not before["partial"]:
            for f in store.all("findings", db, session_id=sid):
                if f.get("check_id") == check_id and f["status"] in ("open", "snoozed"):
                    f.update(status="resolved", updated=now(), resolution_event_id=event["id"])
                    store.put("findings", f, db)
                    for a in store.all("actions", db, session_id=sid):
                        if a.get("finding_id") == f["id"] and a["state"] == "queued":
                            a.update(state="cancelled", reason="Fresh passing check", updated=now())
                            store.put("actions", a, db)
        if status != "passed" or changed:
            finding(store, db, session, "check:"+check_id, "evidence", "Focused check needs attention",
                "Independent check " + status + ("; files changed while it ran" if changed else ""), [event["id"]],
                "Inspect the registered check and resolve the failure within the existing task.", check_id=check_id, origin="rule")
    return event


def reconcile(store, sid):
    session = store.get("sessions", sid)
    project = store.get("projects", session["project_id"])
    if not project["connected"]:
        return
    current = snapshot(project["root"])
    from .engine import Engine
    receipts = [e for e in Engine(store).recent(sid, 200) if e["kind"] == "IndependentCheck"]
    latest = {}
    for e in receipts:
        latest[e["data"]["check_id"]] = e
    with store.transaction() as db:
        session = store.get("sessions", sid, db)
        session["snapshot"] = current
        for check_id, e in latest.items():
            if e["data"]["result"] == "passed" and current["fingerprint"] != e["data"]["after"]["fingerprint"]:
                finding(store, db, session, "stale:"+check_id, "evidence", "A passing check is now stale",
                    "The engineering file fingerprint changed after this check passed. Re-run the registered check before using it as completion evidence.",
                    [e["id"]], "Refresh the registered focused check within your existing permissions.", check_id=check_id, origin="rule")
        if session["status"] == "waiting":
            stops = [e for e in Engine(store).recent(sid, 20) if e["kind"] == "Stop"]
            if stops:
                for check in store.all("checks", db, project_id=project["id"]):
                    if check["enabled"] and check["id"] not in latest:
                        finding(store, db, session, "missing:"+check["id"], "evidence", "Registered completion evidence is missing",
                            "The session stopped without a Damask receipt for the registered check '"+check["name"]+"'. Worker-reported results do not substitute for an independent receipt.",
                            [stops[-1]["id"]], "Request the registered focused check within existing permissions.", check_id=check["id"], origin="rule")
        store.put("sessions", session, db)
